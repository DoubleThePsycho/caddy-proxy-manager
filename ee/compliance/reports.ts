export type ReportFile = { body: string; filename: string; contentType: string; sha256: string; reportId: string };

function fileStem(detail: Pick<StoredReportSummary, "type" | "period" | "id">): string {
  return `${detail.type.replace(/_/g, "-")}-${detail.period.from.slice(0, 10)}_${detail.period.to.slice(0, 10)}-${detail.id}`;
}

/** The report with its integrity block, as downloaded. */
export function reportJson(detail: StoredReportDetail): string {
  return `${JSON.stringify(
    { ...detail.document, integrity: { algorithm: "SHA-256", canonicalization: CANONICALIZATION, sha256: detail.sha256 } },
    null,
    2
  )}\n`;
}

function csvValue(value: ReportCell): string {
  if (Array.isArray(value)) return csvCell(value.join("; "));
  if (typeof value === "boolean") return value ? "yes" : "no";
  return csvCell(value);
}

function csvTable(headers: string[], rows: ReportCell[][]): string {
  return [headers.map((header) => csvCell(header)).join(","), ...rows.map((row) => row.map(csvValue).join(","))].join("\r\n") + "\r\n";
}

/** Sections a CSV export can name; "summary" and "findings" exist in every report. */
export function csvSections(document: ComplianceReportDocument): string[] {
  return ["summary", "findings", ...document.sections.map((item) => item.key)];
}

/**
 * One table of the report as CSV: "summary" (report metadata, its SHA-256 and
 * the summary figures), "findings", or a section. Defaults to the report's
 * first section. Cells a spreadsheet would run as formulas are neutralised.
 */
export function reportCsv(detail: StoredReportDetail, sectionKey: string | null): { body: string; section: string } {
  const document = detail.document;
  const key = sectionKey ?? document.sections[0]?.key ?? "summary";
  if (key === "summary") {
    const rows: ReportCell[][] = [
      ["Report", document.title],
      ["Report id", document.reportId],
      ["Period from (UTC)", document.period.from],
      ["Period to (UTC)", document.period.to],
      ["Generated at (UTC)", document.generatedAt],
      ["Generated by", [document.generatedBy.name, document.generatedBy.email].filter(Boolean).join(" ") || `user ${document.generatedBy.userId}`],
      ["Product", `${document.product.name} ${document.product.version}`],
      ["SHA-256 of the JSON report (canonical)", detail.sha256],
      ["Statement", document.statement],
      ...document.controls.map((control): ReportCell[] => [`Supports ${control.framework} ${control.ref}`, `${control.title}: ${control.how}`]),
      ...document.summary.map((item): ReportCell[] => [item.label, item.value]),
    ];
    return { body: csvTable(["Item", "Value"], rows), section: key };
  }
  if (key === "findings") {
    return {
      body: csvTable(["Severity", "Code", "Subject", "Message"], document.findings.map((item) => [item.severity, item.code, item.subject, item.message])),
      section: key,
    };
  }
  const found = document.sections.find((item) => item.key === key);
  if (!found) throw new ApiValidationError(`section must be one of: ${csvSections(document).join(", ")}`);
  return {
    body: csvTable(found.columns.map((column) => column.label), found.rows.map((row) => found.columns.map((column) => row[column.key] ?? null))),
    section: key,
  };
}

export function reportFile(detail: StoredReportDetail, format: ReportFormat, sectionKey: string | null): ReportFile {
  if (format === "json") {
    return {
      body: reportJson(detail),
      filename: `${fileStem(detail)}.json`,
      contentType: "application/json; charset=utf-8",
      sha256: detail.sha256,
      reportId: detail.reportId,
    };
  }
  const csv = reportCsv(detail, sectionKey);
  return {
    body: csv.body,
    filename: `${fileStem(detail)}-${csv.section.replace(/_/g, "-")}.csv`,
    contentType: "text/csv; charset=utf-8",
    sha256: detail.sha256,
    reportId: detail.reportId,
  };
}

export function parseExportQuery(params: URLSearchParams): { format: ReportFormat; section: string | null } {
  const format = (params.get("format") ?? "json").trim().toLowerCase();
  if (!(REPORT_FORMATS as readonly string[]).includes(format)) throw new ApiValidationError("format must be json or csv");
  const section = params.get("section");
  if (section !== null && !/^[a-z_]{1,64}$/.test(section)) throw new ApiValidationError("section must be a section key of the report");
  return { format: format as ReportFormat, section };
}

export function fileHeaders(file: ReportFile): Record<string, string> {
  return {
    "Content-Type": file.contentType,
    "Content-Disposition": `attachment; filename="${file.filename}"`,
    "Cache-Control": "no-store",
    "X-Content-Type-Options": "nosniff",
    "X-Report-Id": file.reportId,
    "X-Report-Sha256": file.sha256,
  };
}

